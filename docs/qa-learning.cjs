const { chooseDate, chooseTime } = require('./qa-picker-helpers.cjs');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const out = path.resolve(__dirname, '../.expo/qa-learning'); fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'Asia/Ho_Chi_Minh' });
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const button = name => page.getByRole('button', { name, exact: true });
  const tab = name => page.getByRole('tab', { name, exact: true }).last();
  const close = () => button('Đóng').click();
  const openPlan = async () => { await tab('Lịch học').click(); await tab('Tự học').click(); };
  const screenshot = async name => page.screenshot({ path: path.join(out, `${name}.png`) });
  try {
    await page.goto(process.argv[2] || 'http://localhost:8092', { waitUntil: 'networkidle' });
    await page.getByText('Đồ án cuối kỳ Web App', { exact: true }).click();
    await button('Chỉnh sửa bài tập').hover(); await screenshot('task-overview');
    assert.equal(await tab('Đang làm').getAttribute('aria-selected'), 'true');
    await tab('Việc nhỏ').click();
    await page.getByLabel('Việc nhỏ mới', { exact: true }).fill('Đọc lại tiêu chí đánh giá');
    await button('Thêm việc nhỏ').click(); await page.getByRole('checkbox', { name: 'Đọc lại tiêu chí đánh giá', exact: true }).click();
    assert.equal(await page.getByRole('checkbox', { name: 'Đọc lại tiêu chí đánh giá', exact: true }).getAttribute('aria-checked'), 'true');
    await screenshot('task-checklist');
    await tab('Tài liệu').click(); await button('Đọc Yêu cầu đồ án.txt').click();
    await page.getByText('Xem tài liệu', { exact: true }).waitFor(); await close();
    await button('+ Gắn mẫu').click(); await button('Gắn Kiểm tra trước khi nộp.txt').click();
    await button('Đọc Kiểm tra trước khi nộp.txt').waitFor(); await screenshot('task-attachments');
    await button('Gỡ Kiểm tra trước khi nộp.txt').click(); assert.equal(await button('Đọc Kiểm tra trước khi nộp.txt').count(), 0);
    await tab('Buổi học').click(); await screenshot('task-linked-sessions');
    await button('+ Lên lịch').click();
    assert.equal(await page.getByRole('radio', { name: 'Liên kết: Đồ án cuối kỳ Web App', exact: true }).getAttribute('aria-checked'), 'true');
    await page.getByLabel('Nội dung tự học', { exact: true }).fill('Viết phần giới thiệu báo cáo');
    const [dateDay, dateMonth, dateYear] = (await page.getByRole('button', {name:'Chọn ngày học',exact:true}).innerText()).match(/\d{2}\/\d{2}\/\d{4}/)[0].split('/'); const date = [dateYear,dateMonth,dateDay].join('-');
    const future = await page.evaluate(s => { const d = new Date(s + 'T12:00:00'); d.setDate(d.getDate()+1); return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`; }, date);
    await chooseDate(page, 'Ngày học (YYYY-MM-DD)', future);
    await button('Lưu buổi tự học').click(); await page.getByRole('alert').filter({ hasText: 'sau hạn nộp' }).waitFor();
    await chooseDate(page, 'Ngày học (YYYY-MM-DD)', date);
    await chooseTime(page, 'Bắt đầu (HH:mm)', '18:00');
    await button('Lưu buổi tự học').click(); await page.getByRole('alert').filter({ hasText: 'trùng một buổi tự học' }).waitFor();
    await chooseTime(page, 'Bắt đầu (HH:mm)', '19:00');
    await page.getByLabel('Thời lượng (phút)', { exact: true }).fill('25');
    await button('Lưu buổi tự học').click(); await button('Xem buổi Viết phần giới thiệu báo cáo').waitFor();
    await button('Tập trung: Viết phần giới thiệu báo cáo').click();
    await page.getByText('Viết phần giới thiệu báo cáo', { exact: true }).waitFor();
    await screenshot('focus-linked-session');
    // A full timer completion must count once and only complete the selected study session.
    await page.clock.install(); await button('Bắt đầu').click(); await page.clock.fastForward(1500600);
    await page.getByText('Hoàn thành', { exact: true }).first().waitFor();
    await page.clock.fastForward(1500);
    await button('Lịch sử phiên học').click();
    assert.equal(await page.getByText('Viết phần giới thiệu báo cáo · Lập trình Hướng đối tượng • 25 phút', { exact: true }).count(), 1);
    await close();
    await openPlan(); await tab('Hoàn thành').click(); await button('Xem buổi Viết phần giới thiệu báo cáo').click();
    await button('Xem bài tập liên quan').click();
    assert.equal(await tab('Đang làm').getAttribute('aria-selected'), 'true');
    await tab('Việc nhỏ').click(); assert.equal(await page.getByRole('checkbox', { name: 'Đọc lại tiêu chí đánh giá', exact: true }).getAttribute('aria-checked'), 'true'); await close();
    await tab('Tất cả').click(); await button('Lên kế hoạch mới').click();
    await page.getByLabel('Nội dung tự học', { exact: true }).fill('Ôn tập độc lập buổi tối');
    await chooseTime(page, 'Bắt đầu (HH:mm)', '22:00');
    await page.getByLabel('Thời lượng (phút)', { exact: true }).fill('25');
    await button('Lưu buổi tự học').click(); await button('Xem buổi Ôn tập độc lập buổi tối').click();
    await page.getByText('Buổi tự học độc lập', { exact: true }).waitFor(); assert.equal(await button('Xem bài tập liên quan').count(), 0);
    await button('Đánh dấu buổi học đã xong').click(); await close();
    await tab('Theo tuần').click(); await button('Xem buổi Phác thảo ERD cho báo cáo').waitFor(); await screenshot('study-week');
    await tab('Theo ngày').click();
    for (const width of [320, 390, 430, 1280]) {
      await page.setViewportSize({ width, height: 900 });
      await screenshot(`study-plan-${width}`);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await tab('Trang chủ').click(); await page.getByText('Đồ án cuối kỳ Web App', { exact: true }).click();
    await button('Chỉnh sửa bài tập').click(); await button('Xóa bài tập').click(); await button('Xác nhận xóa bài tập').click();
    await openPlan(); await button('Xem buổi Viết phần giới thiệu báo cáo').click();
    await page.getByText('Buổi tự học độc lập', { exact: true }).waitFor(); assert.equal(await button('Xem bài tập liên quan').count(), 0);
    await button('Chỉnh sửa buổi tự học').click(); await button('Xóa buổi tự học').click(); await button('Xác nhận xóa buổi tự học').click();
    assert.equal(await button('Xem buổi Viết phần giới thiệu báo cáo').count(), 0);
    assert.deepEqual(errors, []);
    const result = { passed: true, widths: [320,390,430,1280], checks: ['task detail/checklist persists across flows', 'sample documents attach/read/remove', 'multiple sessions linked to a task', 'deadline and overlapping study validation', 'independent study create/complete', 'daily/weekly study list', 'contextual Pomodoro completion exactly once', 'study completion leaves task status unchanged', 'delete task preserves sessions without dangling link', 'study edit/delete', 'browser console'], errors };
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result));
  } finally { await screenshot('last-state'); fs.writeFileSync(path.join(out, 'console-errors.json'), JSON.stringify(errors)); await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
